"""Pure domain entities and value objects for the RAG Assistant module."""

from dataclasses import dataclass, field
from datetime import UTC, datetime
from uuid import UUID, uuid4


@dataclass(frozen=True)
class ClinicalCitation:
    """Verifiable scientific citation attached to an assistant response."""

    article_id: UUID
    article_slug: str
    article_title: str
    section_heading: str
    scientific_source: str
    source_url: str


@dataclass(frozen=True)
class AssembledClinicalMemory:
    """PII-free longitudinal clinical context assembled for the RAG prompt."""

    life_stage: str
    age_years: int
    diagnosed_conditions: list[str]
    hormonal_method: str
    cycle_summary: str
    detected_correlations: list[str]
    active_treatments: list[str]
    stage_specific_summary: str

    def to_prompt_block(self) -> str:
        """Format PII-free clinical context into a structured Markdown prompt block."""
        conditions_str = (
            ", ".join(self.diagnosed_conditions)
            if self.diagnosed_conditions
            else "ninguna registrada"
        )
        treatments_str = (
            "; ".join(self.active_treatments)
            if self.active_treatments
            else "ninguno activo"
        )
        correlations_str = (
            "\n".join(f"  - {c}" for c in self.detected_correlations)
            if self.detected_correlations
            else "  - Sin correlaciones cíclicas destacadas aún."
        )
        lines = [
            "### Contexto Clínico Longitudinal Anónimo (Cero PII)",
            f"- Etapa biológica activa: {self.life_stage}",
            f"- Edad biológica aproximada: {self.age_years} años",
            f"- Condiciones base diagnosticadas: {conditions_str}",
            f"- Método hormonal actual: {self.hormonal_method}",
            f"- Resumen de ciclo / estado actual: {self.cycle_summary}",
            f"- Tratamientos o suplementos activos: {treatments_str}",
        ]
        if self.stage_specific_summary:
            lines.append(
                f"- Contexto específico de etapa: {self.stage_specific_summary}"
            )
        lines.append("- Correlaciones deterministas detectadas en registros:")
        lines.append(correlations_str)
        return "\n".join(lines)


@dataclass(frozen=True)
class GroundedAssistantResult:
    """Result generated by the grounded clinical LLM or safety interceptor."""

    answer_markdown: str
    citations: list[ClinicalCitation]
    disclaimer_level: str
    suggested_follow_ups: list[str]
    is_emergency_intercepted: bool = False
    safety_triage_category: str = "NONE"


@dataclass
class AssistantConversation:
    """Conversation thread between a user and Cora's clinical RAG assistant."""

    user_id: UUID
    title: str
    life_stage_at_creation: str
    created_at: datetime = field(default_factory=lambda: datetime.now(UTC))
    updated_at: datetime = field(default_factory=lambda: datetime.now(UTC))
    id: UUID = field(default_factory=uuid4)


@dataclass
class AssistantMessage:
    """Individual user or assistant turn within an AssistantConversation."""

    conversation_id: UUID
    role: str
    content_markdown: str
    citations: list[ClinicalCitation] = field(default_factory=list)
    safety_triage_category: str = "NONE"
    is_emergency_intercepted: bool = False
    disclaimer_level: str = "STANDARD"
    suggested_follow_ups: list[str] = field(default_factory=list)
    created_at: datetime = field(default_factory=lambda: datetime.now(UTC))
    id: UUID = field(default_factory=uuid4)
