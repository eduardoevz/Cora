"""Pure domain entities and value objects for the Partner Sharing module."""

import hashlib
from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import StrEnum
from uuid import UUID, uuid4


class PartnerLinkStatus(StrEnum):
    """Lifecycle status of a partner sharing link."""

    ACTIVE = "ACTIVE"
    PAUSED = "PAUSED"
    REVOKED = "REVOKED"


@dataclass(frozen=True)
class SharingScopeMask:
    """Granular permission mask for partner sharing (minimum privilege default)."""

    share_fertility_window: bool = False
    share_pregnancy_milestones: bool = False
    share_mood_and_support_tips: bool = False

    def to_dict(self) -> dict[str, bool]:
        return {
            "share_fertility_window": self.share_fertility_window,
            "share_pregnancy_milestones": self.share_pregnancy_milestones,
            "share_mood_and_support_tips": self.share_mood_and_support_tips,
        }

    @classmethod
    def from_dict(cls, data: dict[str, object] | None) -> "SharingScopeMask":
        if not data:
            return cls()
        return cls(
            share_fertility_window=bool(data.get("share_fertility_window", False)),
            share_pregnancy_milestones=bool(
                data.get("share_pregnancy_milestones", False)
            ),
            share_mood_and_support_tips=bool(
                data.get("share_mood_and_support_tips", False)
            ),
        )


@dataclass
class PartnerInvitation:
    """One-time 24-hour invitation code generated by a user for their partner."""

    owner_user_id: UUID
    invitation_code_hash: str
    expires_at: datetime
    is_redeemed: bool = False
    redeemed_by_user_id: UUID | None = None
    created_at: datetime = field(default_factory=lambda: datetime.now(UTC))
    id: UUID = field(default_factory=uuid4)

    @staticmethod
    def hash_code(code: str) -> str:
        """Calculate SHA-256 digest of normalized invitation code."""
        normalized = code.strip().upper()
        return hashlib.sha256(normalized.encode("utf-8")).hexdigest()

    def verify_code(self, raw_code: str) -> bool:
        """Verify code against stored SHA-256 hash."""
        return self.hash_code(raw_code) == self.invitation_code_hash

    def is_expired(self, current_time: datetime | None = None) -> bool:
        """Check if invitation has expired past 24 hours."""
        ref = current_time or datetime.now(UTC)
        exp = self.expires_at
        if exp.tzinfo is None:
            exp = exp.replace(tzinfo=UTC)
        if ref.tzinfo is None:
            ref = ref.replace(tzinfo=UTC)
        return ref > exp


@dataclass
class PartnerLink:
    """Active or historic sharing link between owner and partner."""

    owner_user_id: UUID
    partner_user_id: UUID
    status: PartnerLinkStatus = PartnerLinkStatus.ACTIVE
    scope: SharingScopeMask = field(default_factory=SharingScopeMask)
    created_at: datetime = field(default_factory=lambda: datetime.now(UTC))
    updated_at: datetime = field(default_factory=lambda: datetime.now(UTC))
    id: UUID = field(default_factory=uuid4)


@dataclass(frozen=True)
class PartnerProjectedView:
    """Projected read-only view delivered to partner, strictly filtered by scope."""

    owner_first_name: str
    current_life_stage: str
    fertility_window_summary: str | None = None
    pregnancy_week: int | None = None
    fetal_milestone: str | None = None
    recent_mood_summary: str | None = None
    support_tips: list[str] = field(default_factory=list)
